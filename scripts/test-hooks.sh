#!/bin/sh
# Test the shared git hooks in .githooks/. POSIX sh.
#
# commit-msg is fed sample messages directly. pre-commit is exercised with
# real commits in a throwaway repository that points at these hooks.
# Exits non-zero if any case gets the wrong result.

root=$(cd "$(dirname "$0")/.." && pwd)
hooks=$root/.githooks
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
passed=0
failed=0

# result <expected pass|fail> <name> <exit code>
result() {
	if [ "$3" -eq 0 ]; then got=pass; else got=fail; fi
	if [ "$got" = "$1" ]; then
		passed=$((passed + 1))
		printf 'ok    %-5s %s\n' "$1" "$2"
	else
		failed=$((failed + 1))
		printf 'FAIL  %-5s %s (got %s)\n' "$1" "$2" "$got"
		sed 's/^/        /' "$tmp/out"
	fi
}

# msg <expected> <name> <message>
msg() {
	printf '%s\n' "$3" >"$tmp/msg"
	"$hooks/commit-msg" "$tmp/msg" >"$tmp/out" 2>&1
	result "$1" "commit-msg: $2" $?
}

echo "commit-msg"
msg pass "conventional title" "feat(hooks): add shared git hooks"
msg pass "title without scope" "docs: explain setup"
msg pass "breaking marker" "feat(api)!: drop the v1 endpoints"
msg pass "merge commit" "Merge branch 'main' into feat/x"
msg pass "revert commit" 'Revert "feat: add x"'
msg pass "fixup commit" "fixup! feat: add x"
msg pass "squash commit" "squash! feat: add x"
msg pass "human co-author" "fix(board): keep column order

Co-Authored-By: Jane Doe <jane@example.com>"
msg pass "attribution only in git comments" "chore: tidy

# Generated with a template; lines starting with # are dropped."
msg pass "attribution only below scissors" "chore: tidy
# ------------------------ >8 ------------------------
+Co-Authored-By: Claude <noreply@anthropic.com>"
msg fail "non-conventional title" "Add shared git hooks"
msg fail "unknown type" "feature: add hooks"
msg fail "subject ends with period" "fix: handle empty input."
msg fail "subject over 72 characters" "docs: $(printf '%073d' 0)"
msg fail "Claude trailer" "feat: add hooks

Co-Authored-By: Claude Opus <noreply@anthropic.com>"
msg fail "lower-case Claude trailer" "feat: add hooks

co-authored-by: claude <someone@example.com>"
msg fail "Copilot trailer" "feat: add hooks

Co-authored-by: Copilot <copilot@github.com>"
msg fail "bot email trailer" "feat: add hooks

Co-Authored-By: Helper <bot@example.com>"
msg fail "robot Generated with line" "feat: add hooks

🤖 Generated with [a tool](https://example.com)"
msg fail "Generated by line" "feat: add hooks

Generated by an assistant"
msg fail "code-assist SOP footer" "feat: add hooks

🤖 Assisted by the code-assist SOP"

# commit <expected> <name> [env assignments...] -- run git commit in the
# throwaway repository and record the result.
commit() {
	_expected=$1 _name=$2
	shift 2
	(cd "$repo" && env "$@" git commit -q -m "test: $_name") >"$tmp/out" 2>&1
	result "$_expected" "pre-commit: $_name" $?
	(cd "$repo" && git reset -q --hard HEAD 2>/dev/null)
}

echo
echo "pre-commit"
repo=$tmp/repo
GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_NOSYSTEM=1
export GIT_CONFIG_GLOBAL GIT_CONFIG_NOSYSTEM
git init -q -b main "$repo"
(
	cd "$repo" || exit 1
	git config user.name Test
	git config user.email test@example.com
	git config core.hooksPath "$hooks"
	echo seed >seed.txt
	git add seed.txt
)

commit fail "commit on main" X=1
commit pass "commit on main with FORGE_ALLOW_MAIN=1" FORGE_ALLOW_MAIN=1
(cd "$repo" && git switch -q -c feat/test)

echo ok >"$repo/ok.txt" && (cd "$repo" && git add ok.txt)
commit pass "commit on a branch" X=1

echo SECRET=1 >"$repo/.env" && (cd "$repo" && git add .env)
commit fail ".env file" X=1

echo key >"$repo/server.pem" && (cd "$repo" && git add server.pem)
commit fail "*.pem file" X=1

echo key >"$repo/id_rsa" && (cd "$repo" && git add id_rsa)
commit fail "id_rsa file" X=1

echo EXAMPLE=1 >"$repo/.env.example" && (cd "$repo" && git add .env.example)
commit pass ".env.example file" X=1

dd if=/dev/zero of="$repo/big.bin" bs=1048576 count=6 2>/dev/null
(cd "$repo" && git add big.bin)
commit fail "file over 5 MB" X=1

mkdir -p "$repo/.agents/skills/demo"
echo demo >"$repo/.agents/skills/demo/SKILL.md"
(cd "$repo" && git add .agents)
commit fail "new skill without symlink" X=1

mkdir -p "$repo/.agents/skills/demo" "$repo/.claude/skills"
echo demo >"$repo/.agents/skills/demo/SKILL.md"
ln -s ../../.agents/skills/demo "$repo/.claude/skills/demo"
(cd "$repo" && git add .agents .claude)
commit pass "new skill with symlink" X=1

echo more >"$repo/.agents/skills/demo/notes.md" && (cd "$repo" && git add .agents)
commit pass "file added to existing skill" X=1

echo
echo "$passed passed, $failed failed"
[ "$failed" -eq 0 ]
